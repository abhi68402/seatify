// Builds js/scene.bundle.js: three.js, the add-ons and Darshan's 3D modules in ONE classic script.
// It is the fallback when the ES-module path fails (blocked file, import maps unsupported, etc.).
// No dependencies: the vendored modules only use plain `import … from` / `export` statements.
//
// Usage:  node tools/bundle-3d.mjs        (rerun after editing scene.js, assets.js, movies.js, layout.js or data.js)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRIES = ['js/scene.js', 'js/assets.js'];

function resolveSpec(spec, fromFile) {
  if (spec === 'three') return join(ROOT, 'vendor/three/build/three.module.js');
  if (spec.startsWith('three/addons/')) return join(ROOT, 'vendor/three/examples/jsm', spec.slice('three/addons/'.length));
  if (spec.startsWith('.')) return resolve(dirname(fromFile), spec);
  throw new Error(`Unsupported import "${spec}" in ${relative(ROOT, fromFile)}`);
}

const IMPORT_RE = /^import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm;
const EXPORT_LIST_RE = /^export\s*\{([^}]*)\};?[ \t]*$/gm;
const EXPORT_DECL_RE = /^export\s+((?:async\s+)?function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;

const mods = new Map(); // abs path -> { id, deps, code }
const order = [];

function load(file) {
  if (mods.has(file)) return mods.get(file);
  const rec = { id: relative(ROOT, file), deps: [], code: '' };
  mods.set(file, rec);
  let src = readFileSync(file, 'utf8');
  if (/\bimport\s*\(|import\.meta/.test(src.replace(/\/\/.*$/gm, ''))) throw new Error(`Dynamic import/import.meta not supported: ${rec.id}`);

  const header = [];
  src = src.replace(IMPORT_RE, (_, clause, spec) => {
    const dep = load(resolveSpec(spec, file));
    rec.deps.push(dep.id);
    const ref = `__m[${JSON.stringify(dep.id)}]`;
    clause = clause.trim();
    let m;
    if ((m = clause.match(/^\*\s+as\s+([\w$]+)$/))) header.push(`const ${m[1]} = ${ref};`);
    else if ((m = clause.match(/^\{([\s\S]*)\}$/))) {
      const parts = m[1].split(',').map((s) => s.trim()).filter(Boolean)
        .map((s) => { const [a, b] = s.split(/\s+as\s+/); return b ? `${a}: ${b}` : a; });
      header.push(`const { ${parts.join(', ')} } = ${ref};`);
    } else throw new Error(`Unsupported import clause "${clause}" in ${rec.id}`);
    return '';
  });

  const exportsOut = [];
  src = src.replace(EXPORT_LIST_RE, (_, list) => {
    for (const s of list.split(',').map((x) => x.trim()).filter(Boolean)) {
      const [local, name] = s.split(/\s+as\s+/);
      exportsOut.push([name || local, local]);
    }
    return '';
  });
  src = src.replace(EXPORT_DECL_RE, (_, kind, name) => { exportsOut.push([name, name]); return `${kind} ${name}`; });
  if (/^export\b/m.test(src)) throw new Error(`Unhandled export form in ${rec.id}`);

  // Getters keep `let` exports live, like real ES module bindings.
  const ret = exportsOut.map(([name, local]) => `get ${name}() { return ${local}; }`).join(', ');
  rec.code = `__m[${JSON.stringify(rec.id)}] = (function () {\n${header.join('\n')}\n${src}\nreturn Object.freeze({ ${ret} });\n})();\n`;
  order.push(rec); // dependencies are pushed first, so this is a valid evaluation order
  return rec;
}

for (const e of ENTRIES) load(join(ROOT, e));

const out = `/* Vyu 3D bundle: GENERATED by tools/bundle-3d.mjs. Do not edit; edit js/*.js and rebuild.
   Contains three.js r160 (MIT, (c) three.js authors) and its examples add-ons. */
(function () {
'use strict';
const __m = {};
${order.map((r) => `// ---- ${r.id}\n${r.code}`).join('\n')}
window.VyuScene = {
  TheatreView: __m['js/scene.js'].TheatreView,
  prepareAssets: __m['js/assets.js'].prepareAssets,
};
})();
`;
const dest = join(ROOT, 'js/scene.bundle.js');
writeFileSync(dest, out);
console.log(`Wrote ${relative(ROOT, dest)}: ${order.length} modules, ${(out.length / 1024).toFixed(0)} KB`);
console.log(order.map((r) => '  ' + r.id).join('\n'));
