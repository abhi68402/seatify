// Generates sw.js: the offline service worker. It precaches every file the site serves, under a
// cache name derived from a hash of their contents, so any change to any file ships a new version.
// No dependencies. Run after changing anything the site serves (the git pre-commit hook does it):
//   node tools/build-sw.mjs
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Everything under these paths is served; nothing else is (docs, tools and the dev server aren't).
const SERVED = ['index.html', 'styles.css', 'manifest.webmanifest', 'favicon.ico', 'js', 'vendor', 'icons'];

const walk = (p) => (statSync(p).isDirectory() ? readdirSync(p).sort().flatMap((n) => (n.startsWith('.') ? [] : walk(join(p, n)))) : [p]);
const files = SERVED.map((p) => join(ROOT, p)).flatMap((p) => { try { return walk(p); } catch { return []; } })
  .map((p) => relative(ROOT, p).split(sep).join('/'));
// Not precached: the single-file 3D fallback (1.4 MB) is only loaded when ES modules fail, so phones
// shouldn't download it up front. When it is needed, the fetch handler below caches it for offline use.
const LAZY = new Set(['js/scene.bundle.js']);
const precache = files.filter((f) => !LAZY.has(f));

const h = createHash('sha256');
for (const f of files) { h.update(f); h.update(readFileSync(join(ROOT, f))); }
// This generator holds the service worker's own code too: changing it must also ship a new VERSION,
// or browsers that already hold a cache under the old VERSION would keep their stale files.
h.update(readFileSync(new URL(import.meta.url)));
const version = h.digest('hex').slice(0, 12);
const bytes = precache.reduce((n, f) => n + statSync(join(ROOT, f)).size, 0);

const sw = `/* Vyu offline service worker. GENERATED by tools/build-sw.mjs: do not edit by hand.
   First visit: downloads and stores every file below (~${(bytes / 1048576).toFixed(1)} MB). After that the
   site opens and runs with no internet. A deploy that changes any file changes VERSION, so
   browsers fetch the new set in the background and switch to it on the next visit. */
const VERSION = '${version}';
const CACHE = 'vyu-' + VERSION;
const FILES = ${JSON.stringify(['./', ...precache], null, 2)};

self.addEventListener('install', (e) => {
  // cache: 'reload' skips the HTTP cache, so a new version never stores stale copies
  e.waitUntil(caches.open(CACHE)
    .then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' }))))
    .then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => (k.startsWith('vyu-') || k.startsWith('seatify-')) && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin || new URL(req.url).pathname.startsWith('/_vercel/')) return; // Vercel analytics scripts: always network, never cached
  if (req.mode === 'navigate') {
    // The page itself: try the network briefly (fresh after a deploy), else the stored copy.
    e.respondWith((async () => {
      const cached = () => caches.match('./', { cacheName: CACHE });
      try {
        const net = await Promise.race([fetch(req), new Promise((_, no) => setTimeout(() => no(new Error('slow')), 3000))]);
        if (net.ok) return net;
        return (await cached()) || net;
      } catch { return (await cached()) || Response.error(); }
    })());
    return;
  }
  // Every other file is versioned in the cache: serve it from there (instant, offline-proof).
  // ignoreSearch: the 3D fallback adds ?v=… to scene.bundle.js.
  e.respondWith((async () => {
    const hit = await caches.match(req, { cacheName: CACHE, ignoreSearch: true });
    if (hit) return hit;
    const net = await fetch(req);
    if (net.ok) (await caches.open(CACHE)).put(req, net.clone());
    return net;
  })());
});
`;
writeFileSync(join(ROOT, 'sw.js'), sw);
console.log(`Wrote sw.js: version ${version}, ${precache.length + 1} precached, ${(bytes / 1048576).toFixed(2)} MB`);
